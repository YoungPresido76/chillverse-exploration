export function getMap(id: number): MapDef {
  return MAPS.find((m) => m.id === id) ?? MAPS[0]!;
}

export function expeditionDurationMs(energyCost: number): number {
  return Math.round(5200 + energyCost * 70);
}

export function isReachable(
  chambers: MapDef["chambers"],
  index: number,
  states: Record<string, ChamberStateLike>,
): boolean {
  if (index === 0) return true;
  const prev = chambers[index - 1];
  return prev ? states[String(prev.id)]?.status === "done" : false;
}

type ChamberStateLike = { status?: string } | undefined;

export function clearedCount(map: MapDef, states: Record<string, ChamberStateLike>): number {
  return map.chambers.filter((c) => states[String(c.id)]?.status === "done").length;
}
